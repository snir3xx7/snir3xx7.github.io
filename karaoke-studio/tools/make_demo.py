"""Generate the original demo song for Karaoke Studio.

Everything here (music, guide melody, lyrics) is original and generated by this
script, so it can be sung over, recorded and exported freely.
Outputs stems (drums, bass, keys, guide vocal) + timed lyrics JSON.
"""
import json, os, subprocess, sys
import numpy as np

SR = 44100
BPM = 100
BEAT = 60 / BPM
BAR = 4 * BEAT
rng = np.random.default_rng(7)
OUT = sys.argv[1] if len(sys.argv) > 1 else "app/demo"

# Structure in bars
# intro 2 | verse 8 | chorus 8 | break 4 | chorus 8 | outro 2
SECTIONS = [("intro", 2), ("verse", 8), ("chorus", 8), ("break", 4), ("chorus", 8), ("outro", 2)]
TOTAL_BARS = sum(n for _, n in SECTIONS)
LENGTH = TOTAL_BARS * BAR + 3.0
N = int(LENGTH * SR)

CHORDS = {  # A minor: Am F C G
    0: [57, 60, 64], 1: [53, 57, 60], 2: [48, 52, 55, 60], 3: [55, 59, 62],
}
ROOTS = {0: 45, 1: 41, 2: 48, 3: 43}

VERSE = [
    "עוד לילה בעיר והאורות דולקים",
    "אני שר לעצמי מילים פשוטות",
    "הרחוב מקשיב והחלון פתוח",
    "ובלב יש מנגינה שלא נגמרת",
]
CHORUS = [
    "שִׁירוּ אִתִּי, שִׁירוּ בְּקוֹל",
    "כל הלילה עוד לפנינו",
    "Sing it loud, sing it free",
    "וזה השיר שלנו, רק אתה ואני",
]

def midi_hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)

def env_adsr(n, a=0.01, d=0.1, s=0.7, r=0.15):
    t = np.arange(n) / SR
    dur = n / SR
    e = np.ones(n) * s
    e[t < a] = t[t < a] / a
    m = (t >= a) & (t < a + d)
    e[m] = 1 - (1 - s) * (t[m] - a) / d
    rel = t > dur - r
    e[rel] *= np.clip((dur - t[rel]) / r, 0, 1)
    return e

def add(buf, start, sig):
    i = int(start * SR)
    if i >= len(buf):
        return
    j = min(len(buf), i + len(sig))
    buf[i:j] += sig[: j - i]

def lowpass(x, cutoff):
    # simple one-pole
    a = np.exp(-2 * np.pi * cutoff / SR)
    y = np.zeros_like(x)
    acc = 0.0
    for k in range(len(x)):
        acc = (1 - a) * x[k] + a * acc
        y[k] = acc
    return y

# ---- instruments -------------------------------------------------------------
def kick():
    n = int(0.35 * SR); t = np.arange(n) / SR
    f = 50 + 90 * np.exp(-t * 30)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t * 9) * 0.9

def snare():
    n = int(0.25 * SR); t = np.arange(n) / SR
    noise = rng.standard_normal(n) * np.exp(-t * 18)
    tone = np.sin(2 * np.pi * 190 * t) * np.exp(-t * 25)
    return (noise * 0.35 + tone * 0.3)

def hat(open_=False):
    n = int((0.18 if open_ else 0.05) * SR); t = np.arange(n) / SR
    x = rng.standard_normal(n)
    x = np.diff(x, prepend=0)  # crude highpass
    return x * np.exp(-t * (14 if open_ else 60)) * 0.12

def bass_note(m, dur):
    n = int(dur * SR); t = np.arange(n) / SR
    f = midi_hz(m)
    x = np.sin(2 * np.pi * f * t) + 0.3 * np.sin(2 * np.pi * 2 * f * t) + 0.1 * np.sign(np.sin(2 * np.pi * f * t))
    return x * env_adsr(n, 0.005, 0.15, 0.6, 0.08) * 0.32

def pad_chord(notes, dur):
    n = int(dur * SR); t = np.arange(n) / SR
    x = np.zeros(n)
    for m in notes:
        f = midi_hz(m + 12)
        for det in (-0.12, 0.0, 0.12):
            ff = f * 2 ** (det / 12)
            x += (2 * ((t * ff) % 1) - 1) * 0.5 + np.sin(2 * np.pi * ff * t)
    x = x / (len(notes) * 3)
    return x * env_adsr(n, 0.25, 0.4, 0.75, 0.5) * 0.22

def pluck(m, dur):
    n = int(dur * SR); t = np.arange(n) / SR
    f = midi_hz(m + 12)
    x = np.sin(2 * np.pi * f * t) + 0.4 * np.sin(2 * np.pi * 3 * f * t) * np.exp(-t * 8)
    return x * np.exp(-t * 4) * 0.12

def voice_note(m, dur):
    n = int(dur * SR); t = np.arange(n) / SR
    f0 = midi_hz(m)
    vib = 1 + 0.006 * np.sin(2 * np.pi * 5.2 * t) * np.clip(t / 0.3, 0, 1)
    ph = 2 * np.pi * np.cumsum(f0 * vib) / SR
    x = np.zeros(n)
    # harmonic series shaped by vowel-ish formants ("ah")
    for h in range(1, 14):
        fh = f0 * h
        amp = np.exp(-((fh - 750) / 300) ** 2) + 0.6 * np.exp(-((fh - 1200) / 350) ** 2) + 0.25 * np.exp(-((fh - 2600) / 500) ** 2) + 0.05
        x += amp * np.sin(h * ph) / h ** 0.3
    x /= 6
    return x * env_adsr(n, 0.04, 0.08, 0.85, 0.12) * 0.55

# ---- arrangement -------------------------------------------------------------
drums = np.zeros(N); bass = np.zeros(N); keys = np.zeros(N); vox = np.zeros(N)

bar = 0
lyrics = []
line_starts = []
for name, nbars in SECTIONS:
    for b in range(nbars):
        t0 = (bar + b) * BAR
        ci = (b) % 4
        chord = CHORDS[ci]; root = ROOTS[ci]
        # keys
        keys_bar = pad_chord(chord, BAR + 0.4) if name != "outro" or b == 0 else pad_chord(CHORDS[0], BAR * 1.5)
        add(keys, t0, keys_bar)
        if name in ("chorus", "break"):
            for k in range(8):
                add(keys, t0 + k * BEAT / 2, pluck(chord[k % len(chord)], BEAT / 2))
        # bass
        if name not in ("intro",):
            if name == "outro" and b == 1:
                pass
            else:
                pattern = [(0, 1.5, root), (1.5, 0.5, root), (2, 1.0, root + 7 if ci != 2 else root + 7), (3, 1.0, root + 12)]
                for st, du, m in pattern:
                    add(bass, t0 + st * BEAT, bass_note(m, du * BEAT * 0.95))
        # drums
        if name == "intro":
            for k in range(8):
                add(drums, t0 + k * BEAT / 2, hat())
        elif name == "outro":
            if b == 0:
                add(drums, t0, kick()); add(drums, t0, hat(True))
        else:
            for k in range(4):
                if k in (0, 2) or (name == "chorus" and k == 3 and b % 2):
                    add(drums, t0 + k * BEAT, kick())
                if k in (1, 3):
                    add(drums, t0 + k * BEAT, snare())
            for k in range(8):
                add(drums, t0 + k * BEAT / 2, hat(open_=(k == 7 and name == "chorus")))
            if name == "break" and b == nbars - 1:
                for k in range(4):
                    add(drums, t0 + (3 + k / 4) * BEAT, snare() * 0.7)
    # lyrics: one line every 2 bars
    if name in ("verse", "chorus"):
        lines = VERSE if name == "verse" else CHORUS
        for li, text in enumerate(lines):
            lt = (bar + li * 2) * BAR + BEAT * 0.5  # pickup on the "and" of 1
            words = text.split()
            span = BEAT * 5.5
            slot = min(BEAT, span / len(words))
            chord = CHORDS[(li * 2) % 4]
            contour = [0, 1, 2, 1, 2, 3, 2, 1, 0]
            scale = [57, 59, 60, 62, 64, 65, 67, 69]  # A minor from A3
            base = 2 if name == "verse" else 4
            wl = []
            for wi, w in enumerate(words):
                wt = lt + wi * slot
                dur = slot * 0.92 if wi < len(words) - 1 else BEAT * 2.2
                deg = base + contour[(wi + li) % len(contour)] - (1 if li % 2 else 0)
                m = scale[min(max(deg, 0), len(scale) - 1)]
                if wi == len(words) - 1:
                    m = chord[-1] if chord[-1] < 70 else chord[0]
                add(vox, wt, voice_note(m, dur))
                wl.append({"t": round(wt, 3), "text": w})
            end = round(wl[-1]["t"] + BEAT * 2.2, 3)
            lyrics.append({"t": wl[0]["t"], "end": end, "text": text, "words": wl})
    bar += nbars

def norm(x, peak):
    m = np.max(np.abs(x)) or 1
    return x / m * peak

drums = norm(drums, 0.55); bass = norm(bass, 0.5); keys = norm(lowpass(keys, 5000), 0.45); vox = norm(vox, 0.6)
mix = drums + bass + keys + vox * 0.9
scale = 0.89 / np.max(np.abs(mix))
stems = {"drums": drums, "bass": bass, "keys": keys, "vocals": vox}

os.makedirs(OUT, exist_ok=True)
def write(name, x):
    import wave
    wav_path = os.path.join(OUT, name + ".wav")
    pcm = np.clip(x * scale, -1, 1)
    with wave.open(wav_path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((pcm * 32767).astype("<i2").tobytes())
    mp3 = os.path.join(OUT, name + ".mp3")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", wav_path, "-codec:a", "libmp3lame", "-b:a", "128k", mp3], check=True)
    os.remove(wav_path)

for k, v in stems.items():
    write(k, v)
write("full-mix", mix)

meta = {
    "title": "לילה בעיר",
    "artist": "קריוקי סטודיו (שיר מקורי להדגמה)",
    "lang": "he",
    "bpm": BPM,
    "duration": round(LENGTH, 2),
    "lyrics": lyrics,
}
with open(os.path.join(OUT, "demo-song.json"), "w", encoding="utf-8") as f:
    json.dump(meta, f, ensure_ascii=False, indent=1)
print("ok", LENGTH, len(lyrics), "lines")
